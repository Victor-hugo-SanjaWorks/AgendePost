import test from 'node:test';
import assert from 'node:assert/strict';
import { domPage } from './qa-dom.mjs';
import { publicationFixture, offlinePublicationAdapter } from './qa-publication-helpers.mjs';

test('QA publication DOM: disabled setup is honest and cannot schedule a real send', async t => {
  const adapter = offlinePublicationAdapter(); adapter.enabled = false;
  const h = await publicationFixture(t, { publishingAdapter: adapter });
  const post = await h.approve(await h.post());
  const page = await domPage(h, t);
  await page.login(h.people.owner);
  await page.navigate('/app/editor/' + post.id, '#editor-publications');
  await page.wait(() => page.$('#publishing-readiness'), 'verified disabled readiness');
  assert.equal(page.$('[data-publishing-action="schedule"]').disabled, true);
  assert.match(page.$('#editor-publications').textContent, /indisponível|desativada/i);
  assert.equal(page.$('.publication-status.published'), null);
  await page.navigate('/app/connections', '#publishing-readiness');
  await page.wait(() => page.text().includes('Ativação pelo operador'), 'connections screen');
  assert.match(page.text(), /Conexão pela Meta indisponível/i);
  assert.match(page.text(), /Nenhuma autorização OAuth foi associada/);
  assert.ok([...page.document.querySelectorAll('[data-publishing-action="connect"]')].every(button => button.disabled));
  assert.match(page.text(), /computador acordado|computador.*acordado/);
  assert.match(page.text(), /não autentica uma conta/i);
  assert.equal(page.document.querySelector('input[type="password"]'), null);
  assert.equal(adapter.calls.length, 0);
  assert.equal(page.errors.length, 0);
});

test('QA publication DOM: exact approval, date-specific offsets, duplicate click and cancellation', async t => {
  const h = await publicationFixture(t), post = await h.approve(await h.post());
  const page = await domPage(h, t);
  await page.login(h.people.editor);
  await page.navigate('/app/editor/' + post.id, '#editor-publications');
  await page.wait(() => page.$('[data-publishing-action="schedule"]') && !page.$('[data-publishing-action="schedule"]').disabled, 'ready exact approved revision');
  page.fill('#post-caption', 'Unsaved edit must not be published');
  assert.equal(page.$('[data-publishing-action="schedule"]').disabled, true);
  page.click('a[href="#/app/posts"]');
  await page.wait(() => page.$('[data-action="confirm-action"]'), 'discard unsaved edit confirmation');
  page.click('[data-action="confirm-action"]');
  await page.wait(() => page.$('#post-list'), 'post list after explicit discard');
  await page.navigate('/app/editor/' + post.id, '#editor-publications');
  await page.wait(() => !page.$('[data-publishing-action="schedule"]')?.disabled, 'saved approved revision reloaded');
  page.click('[data-publishing-action="schedule"]');
  await page.wait(() => page.$('#publication-schedule-form'), 'schedule dialog');
  page.fill('#publication-zone', 'America/New_York');
  page.fill('#publication-date', '2027-03-14T02:30');
  assert.equal(page.$('#publication-offset').options.length, 0, 'A nonexistent DST wall-clock time must not be normalized silently');
  assert.match(page.$('#publication-time-preview').textContent, /não existe/);
  page.fill('#publication-date', '2026-11-01T01:30');
  assert.deepEqual([...page.$('#publication-offset').options].map(x => x.value).filter(Boolean).sort(), ['-04:00', '-05:00']);
  assert.equal(page.$('#publication-offset').value, '');
  assert.match(page.$('#publication-time-preview').textContent, /ambíguo/);
  page.click('[data-action="dialog-close"]');
  assert.equal(page.$('#publication-schedule-form'), null);
  assert.equal((await h.jobs(post)).length, 0);
  page.click('[data-publishing-action="schedule"]');
  page.fill('#publication-zone', 'UTC');
  page.fill('#publication-date', new Date(Date.now() + 600_000).toISOString().slice(0, 16));
  page.$('input[name="confirmSend"]').checked = true;
  const button = page.$('#publication-schedule-form button[type="submit"]'); button.click(); button.click();
  await page.wait(() => !page.$('#publication-schedule-form') && page.document.querySelectorAll('[data-publication-id]').length === 2, 'one job per target and only one enqueue');
  const jobs = await h.jobs(post); assert.equal(jobs.length, 2);
  assert.ok(jobs.every(j => j.revision === post.revision && j.status === 'scheduled' && j.remoteId === null));
  assert.equal(adapterCalls(h), 0);
  assert.equal(page.document.querySelectorAll('.publication-status.published').length, 0);
  const first = jobs[0];
  page.click(`[data-publishing-action="reschedule"][data-job-id="${first.id}"]`);
  await page.wait(() => page.$('#publication-schedule-form'), 'reschedule dialog');
  page.fill('#publication-date', new Date(Date.now() + 1_200_000).toISOString().slice(0, 16));
  page.$('input[name="confirmSend"]').checked = true;
  page.click('#publication-schedule-form button[type="submit"]');
  await page.wait(() => !page.$('#publication-schedule-form'), 'reschedule completed');
  await page.wait(() => (page.$(`[data-publication-id="${first.id}"] time`)?.dateTime ?? '') !== first.scheduledAt, 'rescheduled date displayed');
  page.click(`[data-publishing-action="cancel"][data-job-id="${first.id}"]`);
  await page.wait(() => page.$('[data-action="confirm-action"]'), 'cancellation confirmation');
  page.click('[data-action="confirm-action"]');
  await page.wait(() => page.$(`[data-publication-id="${first.id}"] .publication-status.cancelled`), 'server-confirmed cancellation');
  assert.equal((await h.jobs(post)).find(j => j.id === first.id).status, 'cancelled');
  assert.equal(page.errors.length, 0);
});

function adapterCalls(h) { return h.adapter.calls.length; }
