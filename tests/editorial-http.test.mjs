import test from 'node:test';
import assert from 'node:assert/strict';
import sharp from 'sharp';
import { randomUUID } from 'node:crypto';
import { harness, verified, invite, route, idempotency, multipart } from './qa-helpers.mjs';

test('editorial HTTP: persisted CRUD, optimistic versions, review, archive, target boundaries and private media', async t => {
  const h = await harness(t);
  const owner = await verified(h, 'editorial-owner');
  const reviewer = await verified(h, 'editorial-reviewer');
  const tenant = await owner.client.ok('POST','/api/v1/tenants',{name:'Editorial real fixture',slug:'editorial-fixture',timezone:'America/Sao_Paulo'},idempotency());
  let brand = await owner.client.ok('POST',`/api/v1/tenants/${tenant.id}/workspaces`,{name:'Primary brand',channels:[{platform:'instagram',label:'Disconnected target'}]},idempotency());
  const brand2 = await owner.client.ok('POST',`/api/v1/tenants/${tenant.id}/workspaces`,{name:'Other brand'},idempotency());
  const path = suffix => route(tenant,brand,suffix);
  const channels = await owner.client.ok('GET',path('/channels'));
  let image, post;

  await t.test('empty real organization, disconnected target, strict inputs and atomic brand quota', async () => {
    assert.deepEqual(await owner.client.ok('GET',path('/posts')),[]);
    assert.equal(channels[0].connectionStatus,'not_connected');
    const third = await owner.client.request('POST',`/api/v1/tenants/${tenant.id}/workspaces`,{name:'Over quota'},idempotency());
    assert.equal(third.status,409,third.body);
    assert.equal(h.db.prepare('SELECT count(*) AS n FROM workspaces WHERE tenant_id=?').get(tenant.id).n,2);
    const unknown=await owner.client.request('POST',path('/channels'),{platform:'instagram',label:'Fake connected',connectionStatus:'connected'});
    assert.ok([400,422].includes(unknown.status),unknown.body);
    const page=await owner.client.request('GET',`/api/v1/tenants/${tenant.id}/workspaces?limit=1`);
    assert.equal(page.data.length,1);assert.ok(page.json.meta.nextCursor);
    const next=await owner.client.request('GET',`/api/v1/tenants/${tenant.id}/workspaces?limit=1&cursor=${page.json.meta.nextCursor}`);
    assert.equal(next.data.length,1);assert.notEqual(next.data[0].id,page.data[0].id);assert.equal(next.json.meta.nextCursor,null);
    assert.equal((await owner.client.request('GET',path('/posts?cursor=invalid'))).status,422);
  });
  await t.test('HTTP uploads normalize real bytes, idempotency cannot bypass scope or consume quota twice', async () => {
    const source=await sharp({create:{width:24,height:16,channels:3,background:'#cceeff'}}).jpeg().withExif({IFD0:{Copyright:'Remove this private marker'}}).toBuffer();
    const form=multipart(Buffer.concat([source,Buffer.from('trailingPrivatePayload')]),{filename:'../../test.jpg',mime:'image/jpeg'});
    const key=randomUUID();
    image=await owner.client.ok('POST',path('/media'),form.payload,{headers:{...form.headers,'idempotency-key':key}});
    const repeated=await owner.client.ok('POST',path('/media'),form.payload,{headers:{...form.headers,'idempotency-key':key}});
    assert.equal(repeated.id,image.id);
    assert.equal(image.originalName,'test.jpg');
    const stored=await owner.client.request('GET',image.contentUrl);
    assert.equal(stored.status,200);assert.equal(stored.headers['cache-control'],'private, no-store');
    assert.equal((await sharp(stored.raw).metadata()).exif,undefined);assert.ok(!stored.raw.includes(Buffer.from('trailingPrivatePayload')));
    assert.equal(h.db.prepare('SELECT count(*) AS n FROM media WHERE tenant_id=?').get(tenant.id).n,1);
    assert.equal(h.db.prepare('SELECT length(bytes) AS n FROM media_blobs WHERE tenant_id=?').get(tenant.id).n,image.sizeBytes);
    const bad=multipart(source,{mime:'image/png'});
    assert.equal((await owner.client.request('POST',path('/media'),bad.payload,{headers:bad.headers})).status,422);
    const payload=Buffer.from('--bad\r\nContent-Disposition: form-data; name="other"\r\n\r\nextra\r\n--bad--\r\n');
    assert.equal((await owner.client.request('POST',path('/media'),payload,{headers:{'content-type':'multipart/form-data; boundary=bad'}})).status,422);
    const oversize=multipart(Buffer.alloc(5*1024*1024+1),{mime:'image/png'});
    assert.equal((await owner.client.request('POST',path('/media'),oversize.payload,{headers:oversize.headers})).status,413);
    const total=Buffer.alloc(5*1024*1024+65537,32);
    assert.equal((await owner.client.request('POST',path('/media'),total,{headers:{'content-type':'multipart/form-data; boundary=bad'}})).status,413);
    assert.equal(h.db.prepare('SELECT count(*) AS n FROM media WHERE tenant_id=?').get(tenant.id).n,1);
  });
  await t.test('post idempotency, concurrency and retained media revision history', async () => {
    const key=idempotency();
    const body={title:'Original title',caption:'Original content',mediaIds:[image.id],channelIds:[channels[0].id],tags:['campaign']};
    post=await owner.client.ok('POST',path('/posts'),body,key);
    assert.equal((await owner.client.ok('POST',path('/posts'),body,key)).id,post.id);
    assert.equal((await owner.client.request('POST',path('/posts'),{...body,title:'Different'},key)).status,409);
    const results=await Promise.all(['One','Two'].map(title=>owner.client.request('PATCH',path(`/posts/${post.id}`),{expectedRevision:post.revision,title})));
    assert.deepEqual(results.map(r=>r.status).sort(),[200,409]);post=results.find(r=>r.status===200).data;
    post=await owner.client.ok('PATCH',path(`/posts/${post.id}`),{expectedRevision:post.revision,mediaIds:[]});
    assert.equal((await owner.client.request('DELETE',path(`/media/${image.id}`))).status,409);
    const revisions=await owner.client.ok('GET',path(`/posts/${post.id}/revisions`));
    assert.equal(revisions.length,3);assert.equal(revisions[0].content.mediaIds[0],image.id);
    assert.equal((await owner.client.request('POST',path(`/posts/${post.id}/duplicate`),{})).status,422);
    const duplicate=await owner.client.ok('POST',path(`/posts/${post.id}/duplicate`),{},idempotency());
    assert.equal(duplicate.status,'draft');assert.equal(duplicate.revision,1);assert.equal(duplicate.approvedRevision,null);
    assert.equal((await owner.client.request('PATCH',path(`/channels/${channels[0].id}`),{expectedVersion:1,archived:true})).status,409);
  });
  await t.test('independent approval, planning, changed schedule invalidation and restore enforce exact policy', async () => {
    await invite(h,owner.client,tenant.id,reviewer,'reviewer',[brand.id]);
    const transition=async(actor,action,extra={})=>actor.client.request('POST',path(`/posts/${post.id}/transitions`),{action,expectedRevision:post.revision,...extra},idempotency());
    post=(await transition(owner,'submit_review')).data;
    assert.equal((await transition(owner,'approve')).status,403);
    post=(await transition(reviewer,'approve')).data;assert.equal(post.status,'approved');
    post=(await transition(owner,'plan',{scheduledAt:'2099-01-01T10:00:00-03:00',scheduledTimezone:'America/Sao_Paulo'})).data;
    assert.equal(post.status,'planned');assert.equal(post.scheduledAt,'2099-01-01T13:00:00.000Z');
    post=await owner.client.ok('PATCH',path(`/posts/${post.id}`),{expectedRevision:post.revision,scheduledAt:'2099-01-02T10:00:00-03:00',scheduledTimezone:'America/Sao_Paulo'});
    assert.equal(post.status,'draft');assert.equal(post.approvedRevision,null);
    assert.equal((await transition(owner,'plan',{scheduledAt:'2099-01-03T10:00:00-03:00',scheduledTimezone:'America/Sao_Paulo'})).status,409);
    post=(await transition(owner,'archive')).data;assert.equal(post.status,'archived');
    assert.equal((await owner.client.request('PATCH',path(`/posts/${post.id}`),{expectedRevision:post.revision,title:'Edit archived'})).status,409);
    post=(await transition(owner,'restore')).data;assert.equal(post.status,'draft');assert.equal(post.scheduledAt,null);
    const events=await owner.client.ok('GET',path(`/posts/${post.id}/history`));
    assert.ok(events.some(e=>e.action==='plan'));assert.ok(events.some(e=>e.action==='restore'));
    const report=await reviewer.client.ok('GET',`/api/v1/tenants/${tenant.id}/reports/editorial`);
    assert.equal(report.source,'editorial-only');assert.ok(!JSON.stringify(report).includes(brand2.id));
  });
  await t.test('brand archive/restore is versioned, blocks mutation and never loses data', async () => {
    brand=await owner.client.ok('PATCH',path(''),{expectedVersion:brand.version,archived:true});
    assert.ok(brand.archivedAt);assert.equal((await owner.client.request('POST',path('/posts'),{title:'Blocked'})).status,409);
    assert.equal((await owner.client.request('PATCH',path(''),{expectedVersion:1,archived:false})).status,409);
    assert.equal((await owner.client.ok('GET',path(`/posts/${post.id}`))).id,post.id);
    brand=await owner.client.ok('PATCH',path(''),{expectedVersion:brand.version,archived:false});assert.equal(brand.archivedAt,null);
    const exported = await owner.client.request('GET', `/api/v1/tenants/${tenant.id}/export/editorial`);
    assert.equal(exported.status, 200, exported.body);
    const payload = JSON.parse(exported.body);
    assert.equal(payload.source, 'editorial-only'); assert.equal(payload.mediaBytesIncluded, false);
    assert.equal(payload.media.length, 1); assert.ok(payload.revisions.length > payload.posts.length);
    assert.doesNotMatch(exported.body, /authorId|actorId|reviewerId|updatedBy|password_hash|csrfToken/);
    assert.deepEqual(h.db.prepare('PRAGMA foreign_key_check').all(),[]);
    assert.ok(h.db.prepare("SELECT count(*) AS n FROM audit_events WHERE tenant_id=? AND action='post.plan'").get(tenant.id).n>0);
  });
});
