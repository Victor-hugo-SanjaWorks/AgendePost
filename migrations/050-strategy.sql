-- Brand-scoped strategy. All external observations are entered by a user, never fetched.
CREATE TABLE strategy_entries (
  tenant_id TEXT NOT NULL,
  workspace_id TEXT NOT NULL,
  id TEXT NOT NULL,
  quadrant TEXT NOT NULL CHECK(quadrant IN ('strength','weakness','opportunity','threat')),
  title TEXT NOT NULL CHECK(length(title) BETWEEN 1 AND 160),
  description TEXT NOT NULL DEFAULT '' CHECK(length(description)<=2000),
  classification TEXT NOT NULL CHECK(classification IN ('hypothesis','evidence')),
  source_type TEXT NOT NULL CHECK(source_type IN ('user_provided','public_source')),
  source_url TEXT,
  observed_on TEXT,
  source_notes TEXT NOT NULL DEFAULT '' CHECK(length(source_notes)<=2000),
  archived_at TEXT,
  version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
  created_by TEXT NOT NULL,
  updated_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(tenant_id,workspace_id,id),
  FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
  FOREIGN KEY(tenant_id,created_by) REFERENCES memberships(tenant_id,user_id),
  FOREIGN KEY(tenant_id,updated_by) REFERENCES memberships(tenant_id,user_id),
  CHECK(classification!='evidence' OR (observed_on IS NOT NULL AND (source_url IS NOT NULL OR length(source_notes)>0))),
  CHECK(source_type!='public_source' OR source_url IS NOT NULL)
) STRICT;
CREATE INDEX strategy_entries_scope ON strategy_entries(tenant_id,workspace_id,archived_at,id);
CREATE TABLE strategy_competitors (
  tenant_id TEXT NOT NULL,
  workspace_id TEXT NOT NULL,
  id TEXT NOT NULL,
  name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 120),
  website_url TEXT,
  profile_url TEXT,
  platform TEXT NOT NULL DEFAULT 'other' CHECK(platform IN ('instagram','facebook','linkedin','tiktok','youtube','pinterest','threads','x','other')),
  positioning TEXT NOT NULL DEFAULT '' CHECK(length(positioning)<=1000),
  audience TEXT NOT NULL DEFAULT '' CHECK(length(audience)<=1000),
  formats TEXT NOT NULL DEFAULT '' CHECK(length(formats)<=1000),
  followers INTEGER CHECK(followers IS NULL OR followers BETWEEN 0 AND 10000000000),
  posts_observed INTEGER CHECK(posts_observed IS NULL OR posts_observed BETWEEN 0 AND 1000000),
  observation_days INTEGER CHECK(observation_days IS NULL OR observation_days BETWEEN 1 AND 365),
  source_type TEXT NOT NULL CHECK(source_type IN ('user_provided','public_source')),
  source_url TEXT,
  observed_on TEXT NOT NULL,
  source_notes TEXT NOT NULL CHECK(length(source_notes) BETWEEN 1 AND 2000),
  archived_at TEXT,
  version INTEGER NOT NULL DEFAULT 1 CHECK(version>0),
  created_by TEXT NOT NULL,
  updated_by TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(tenant_id,workspace_id,id),
  FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
  FOREIGN KEY(tenant_id,created_by) REFERENCES memberships(tenant_id,user_id),
  FOREIGN KEY(tenant_id,updated_by) REFERENCES memberships(tenant_id,user_id),
  CHECK((posts_observed IS NULL)=(observation_days IS NULL)),
  CHECK(source_type!='public_source' OR source_url IS NOT NULL)
) STRICT;
CREATE INDEX strategy_competitors_scope ON strategy_competitors(tenant_id,workspace_id,archived_at,id);
CREATE TABLE strategy_revisions (
  tenant_id TEXT NOT NULL,
  workspace_id TEXT NOT NULL,
  entity_type TEXT NOT NULL CHECK(entity_type IN ('entry','competitor')),
  entity_id TEXT NOT NULL,
  version INTEGER NOT NULL CHECK(version>0),
  actor_id TEXT NOT NULL,
  snapshot TEXT NOT NULL CHECK(json_valid(snapshot)),
  created_at TEXT NOT NULL,
  PRIMARY KEY(tenant_id,workspace_id,entity_type,entity_id,version),
  FOREIGN KEY(tenant_id,workspace_id) REFERENCES workspaces(tenant_id,id),
  FOREIGN KEY(tenant_id,actor_id) REFERENCES memberships(tenant_id,user_id)
) STRICT;
